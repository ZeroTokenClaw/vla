BT = chr(96)
lines = []
def L(s):
    lines.append(s)

L("import { createPrng } from './prng'")
L("")
L("function makeTrajectory(rng, frames = 24, dof = 7) {")
L("  const joints = []")
L("  const gripper = []")
L("  const tSec = []")
L("  for (let i = 0; i < frames; i += 1) {")
L("    joints.push(")
L("      Array.from({ length: dof }, (_, j) =>")
L("        Number((rng.next() * 1.2 - 0.4 + j * 0.01).toFixed(4)),")
L("      ),")
L("    )")
L("    gripper.push(Number(rng.next().toFixed(3)))")
L("    tSec.push(Number((i / 10).toFixed(2)))")
L("  }")
L("  return { joints, gripper, tSec, hz: 10 }")
L("}")
L("")
L("/**")
L(" * Element DataLink VLA episodes - independent seed; trajectory keys:")
L(" * trajectory.{joints,gripper,tSec}")
L(" */")
L("export function seedVlaEpisodes(hand, seed = 0xD11A7E01) {")
L("  const rng = createPrng(seed ^ 0x3333)")
L("  const scenes = ['kitchen_counter', 'lab_bench', 'warehouse_bin', 'office_desk']")
L("  const plans = ['pick_place_std', 'open_drawer', 'wipe_surface', 'sort_parts']")
L("  const modes = ['teleop', 'scripted', 'human_demo', 'mixed']")
L("  const statuses = ['ready', 'annotating', 'done']")
L("  const videos = [1, 2, 3, 4, 5, 6].map((n) => ({")
L("    videoUrl: " + BT + "/samples/video/ep_0${n}.mp4" + BT + ",")
L("    imageUrl: " + BT + "/samples/video/ep_0${n}_poster.jpg" + BT + ",")
L("  }))")
L("")
L("  const out = hand.map((t, idx) => {")
L("    const media = videos[idx % videos.length]")
L("    const usesSharedBin =")
L("      typeof t.videoUrl === 'string' && t.videoUrl.includes('bin_pick')")
L("    return {")
L("      ...t,")
L("      trajectory: t.trajectory || makeTrajectory(rng, Math.min(30, t.totalFrames || 24)),")
L("      videoUrl: usesSharedBin ? media.videoUrl : t.videoUrl,")
L("      imageUrl: usesSharedBin ? media.imageUrl : t.imageUrl,")
L("    }")
L("  })")
L("")
L("  const used = new Set(out.map((t) => t.id))")
L("  let seq = out.length + 1")
L("  while (out.length < 56) {")
L("    const media = videos[(seq - 1) % videos.length]")
L("    const frames = rng.int(80, 140)")
L("    let id = " + BT + "DL-VLA-2026-${String(seq).padStart(3, '0')}" + BT)
L("    while (used.has(id)) {")
L("      seq += 1")
L("      id = " + BT + "DL-VLA-2026-${String(seq).padStart(3, '0')}" + BT)
L("    }")
L("    used.add(id)")
L("    const scene = rng.pick(scenes)")
L("    const plan = rng.pick(plans)")
L("    const mode = rng.pick(modes)")
L("    const status = rng.pick(statuses)")
L("    const day = rng.int(1, 4)")
L("    out.push({")
L("      id,")
L("      name: " + BT + "数联采集episode-${seq}" + BT + ",")
L("      scene,")
L("      plan,")
L("      mode,")
L("      actionTemplateIds: ['tpl-reach', 'tpl-grasp', 'tpl-place'],")
L("      personnelIds: [rng.pick(['u-dl-annotator', 'u-dl-annotator-2'])],")
L("      instruction: " + BT + "脱敏指令：完成 episode ${seq} 抓取放置。场景=${scene} 方案=${plan}" + BT + ",")
L("      videoUrl: media.videoUrl,")
L("      imageUrl: media.imageUrl,")
L("      fps: 10,")
L("      totalFrames: frames,")
L("      durationSec: Number((frames / 10).toFixed(1)),")
L("      status,")
L("      createdAt: " + BT + "2026-11-0${day} ${String(rng.int(8, 18)).padStart(2, '0')}:${String(rng.int(0, 59)).padStart(2, '0')}:00" + BT + ",")
L("      actions: [],")
L("      issuesSeed: [],")
L("      trajectory: makeTrajectory(rng, 24),")
L("    })")
L("    seq += 1")
L("  }")
L("  return out")
L("}")
L("")
L("export { makeTrajectory }")
L("")

path = r'E:\omp\vla\vla-demo-element\src\mock\seed\vla.js'
open(path, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
